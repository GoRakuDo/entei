/// The single-user profile row.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct UserProfile {
    pub handle: String,
    pub display_name: String,
    pub bio: Option<String>,
    pub avatar_url: Option<String>,
    pub updated_at: i64,
}

/// Input for `db_upsert_profile`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct UserProfileInput {
    pub handle: String,
    pub display_name: String,
    pub bio: Option<String>,
    pub avatar_url: Option<String>,
    pub updated_at: i64,
}

/// One key/value pair of the generic settings store.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct KvEntry {
    pub key: String,
    pub value: String,
}

/// Batch payload for the one-shot `db_migrate_v1` import.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct MigrationPayloadV1 {
    pub posts: Vec<TimelinePost>,
    pub watch_history: Vec<WatchHistoryItem>,
    pub watch_sessions: Vec<WatchSessionItem>,
    pub mining_archive: Vec<MiningArchiveItem>,
    pub profile: Option<UserProfile>,
    pub kv: Vec<KvEntry>,
}
