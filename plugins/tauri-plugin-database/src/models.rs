//! Data models shared by the SQLite layer and the Tauri command boundary.
//!
//! Every struct is `Serialize` + `Deserialize` so the same type can be sent to
//! the webview as a command result and accepted back as a command argument
//! (the `*_input` variants), keeping the web/Rust contract in one place.

use serde::{Deserialize, Serialize};

/// A timeline post (top-level or reply).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TimelinePost {
    pub id: String,
    pub author_handle: String,
    pub author_name: String,
    pub author_avatar: String,
    pub content: String,
    pub created_at: i64,
    pub likes: i64,
    pub liked_by_me: bool,
    pub reply_count: i64,
    pub parent_id: Option<String>,
}

/// Input for `db_create_timeline_post`. The `id` is generated by the Rust side.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TimelinePostInput {
    pub author_handle: String,
    pub author_name: String,
    pub author_avatar: String,
    pub content: String,
    pub created_at: i64,
    pub parent_id: Option<String>,
}

/// One entry of watch history (one media the user has watched).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WatchHistoryItem {
    pub media_id: String,
    pub title: String,
    pub title_native: Option<String>,
    pub episode: Option<i64>,
    pub source: String,
    pub watched_at: i64,
    pub duration: Option<f64>,
    pub position: Option<f64>,
    pub poster_url: Option<String>,
    pub poster_status: Option<String>,
    pub anilist_id: Option<i64>,
    pub tmdb_id: Option<i64>,
}

/// Input for `db_upsert_watch_history`. Keyed by `media_id`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WatchHistoryInput {
    pub media_id: String,
    pub title: String,
    pub title_native: Option<String>,
    pub episode: Option<i64>,
    pub source: String,
    pub watched_at: i64,
    pub duration: Option<f64>,
    pub position: Option<f64>,
    pub poster_url: Option<String>,
    pub poster_status: Option<String>,
    pub anilist_id: Option<i64>,
    pub tmdb_id: Option<i64>,
}

/// One viewing session (a single sit-down with a media).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WatchSessionItem {
    pub id: String,
    pub media_id: String,
    pub title: String,
    pub start_time: i64,
    pub end_time: i64,
    pub duration: i64,
    pub cues_mined: i64,
    pub mined_sentences: Vec<String>,
}

/// Input for `db_save_watch_session`.
///
/// `id` is optional so a client can drive a **stable** session identity: the
/// web layer generates one session id per sit-down and re-saves the same row
/// as the session progresses (start, media attach, mined sentence, end). When
/// `id` is `None` the Rust side generates a fresh id (server-authoritative),
/// which is the right default for a one-shot save. When it is `Some`, the
/// upsert keys on that id so repeated saves update one row instead of
/// multiplying rows for a single session.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WatchSessionInput {
    pub id: Option<String>,
    pub media_id: String,
    pub title: String,
    pub start_time: i64,
    pub end_time: i64,
    pub duration: i64,
    pub cues_mined: i64,
    pub mined_sentences: Vec<String>,
}

/// One mined card stored in the local archive.
